_GENERATED_MARKER = re.compile(r"(Code generated .* DO NOT EDIT|@generated|<auto-generated|autogenerated file)", re.I)


def is_generated(fd: FileDiff) -> bool:
    base = posixpath.basename(fd.path).lower()
    if base in _LOCKFILES or _GENERATED.search(fd.path):
        return True
    first_lines = [ln.text for h in fd.hunks[:1] for ln in h.lines[:12]]
    return any(_GENERATED_MARKER.search(t) for t in first_lines)


_CODE_EXT = {
    ".go", ".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java", ".kt", ".kts", ".scala", ".rb", ".rs", ".c",
    ".cc", ".cpp", ".h", ".hpp", ".cs", ".swift", ".m", ".mm", ".php", ".ex", ".exs", ".erl", ".clj", ".dart", ".lua",
}


def category(fd: FileDiff) -> str:
    p = fd.path
    if is_generated(fd):
        return "generated"
    is_code = posixpath.splitext(p)[1].lower() in _CODE_EXT
    for name, rx in (("test", _TEST), ("docs", _DOCS), ("infra", _INFRA), ("schema", _SCHEMA),
                     ("types", _TYPES), ("api", _API), ("ui", _UI), ("config", _CONFIG)):
        # A source file under config/ or docs/ is still code (e.g. Go's internal/config package).
        if is_code and name in ("config", "docs"):
            continue
        if rx.search(p):
            return name
    return "core"


def is_sensitive(path: str) -> bool:
    return bool(_SENSITIVE.search(path))


def minutes(fd: FileDiff, cat: str) -> float:
    changed = fd.additions + fd.deletions
    if cat == "generated" or fd.binary:
        return 0.5
    rate = {"docs": 80, "test": 60, "config": 60}.get(cat, 25)
    return max(0.5, round((changed / rate + 0.5) * 2) / 2)


_TEST_STEM = re.compile(r"^(test_)?(.+?)([._-]?(test|tests|spec|Test|Tests|Spec))?$")


def _stem(path: str) -> str:
    base = posixpath.basename(path)
    stem = base.split(".")[0]
    m = _TEST_STEM.match(stem)
    return (m.group(2) if m else stem).lower()


def pair_tests(paths_by_cat: dict[str, str]) -> dict[str, str]:
    """Map test file → the changed source file it most likely covers (same stem, nearest directory)."""
    sources: dict[str, list[str]] = {}
    for p, cat in paths_by_cat.items():
        if cat not in ("test", "docs", "generated"):
            sources.setdefault(posixpath.basename(p).split(".")[0].lower(), []).append(p)
    pairs: dict[str, str] = {}
    for p, cat in paths_by_cat.items():
        if cat != "test":
            continue
        candidates = sources.get(_stem(p), [])
        if not candidates:
            continue
        tdir = posixpath.dirname(p)

        def distance(src: str) -> int:
            common = posixpath.commonpath([tdir, posixpath.dirname(src)]) if tdir and posixpath.dirname(src) else ""
            return len(tdir.split("/")) + len(posixpath.dirname(src).split("/")) - 2 * len(common.split("/") if common else [])

        pairs[p] = min(candidates, key=distance)
    return pairs
